import axios from 'axios';

// ============================================================
// Axios 인스턴스
// ============================================================

const api = axios.create({
    baseURL: 'http://localhost:8080/api/v1',
    timeout: 5000,
    headers: {
        'Content-Type': 'application/json',
    },
});


// ============================================================
// 중복 알림 방지
// ============================================================

// 같은 권한 오류가 짧은 시간 안에 여러 번 발생해도
// alert는 한 번만 표시
let is403AlertShowing = false;


// ============================================================
// Request Interceptor
// ============================================================

api.interceptors.request.use(
    (config) => {

        const token = localStorage.getItem('accessToken');

        if (token) {
            config.headers.Authorization = `Bearer ${token}`;
        }

        return config;
    },

    (error) => {
        return Promise.reject(error);
    }
);


// ============================================================
// Response Interceptor
// ============================================================

api.interceptors.response.use(

    // --------------------------------------------------------
    // 정상 응답
    // --------------------------------------------------------

    (response) => {
        return response;
    },


    // --------------------------------------------------------
    // 에러 응답
    // --------------------------------------------------------

    (error) => {

        // ====================================================
        // 서버 응답이 있는 경우
        // ====================================================

        if (error.response) {

            const {
                status,
                data
            } = error.response;

            const serverMessage =
                data?.message ||
                data?.error ||
                '처리 중 오류가 발생했습니다.';


            // ==================================================
            // 400 Bad Request
            // ==================================================

            if (status === 400) {

                alert(
                    `[잘못된 요청] ${serverMessage}`
                );
            }


            // ==================================================
            // 401 Unauthorized
            // ==================================================

            else if (status === 401) {

                /*
                 * 이미 로그아웃된 상태에서 발생한 401을
                 * 계속 alert하지 않도록 처리
                 */

                const token =
                    localStorage.getItem('accessToken');

                if (token) {

                    alert(
                        '로그인 세션이 만료되었거나 인증되지 않았습니다. 다시 로그인해 주세요.'
                    );

                    localStorage.removeItem('accessToken');
                    localStorage.removeItem('tokenType');
                    localStorage.removeItem('user');

                    // 필요하면 로그인 페이지로 이동
                    // window.location.href = '/login';
                }
            }


            // ==================================================
            // 403 Forbidden
            // ==================================================

            else if (status === 403) {

                /*
                 * 여러 API 요청이 동시에 403을 반환하더라도
                 * alert는 한 번만 표시
                 */

                if (!is403AlertShowing) {

                    is403AlertShowing = true;

                    alert(
                        '해당 기능에 대한 접근 권한이 없습니다.'
                    );

                    /*
                     * alert가 닫힌 후 다음 403은 다시
                     * 정상적으로 알림을 띄울 수 있도록 초기화
                     */
                    setTimeout(() => {
                        is403AlertShowing = false;
                    }, 300);
                }
            }


            // ==================================================
            // 404 Not Found
            // ==================================================

            else if (status === 404) {

                alert(
                    `[요청 경로 없음] ${serverMessage}`
                );
            }


            // ==================================================
            // 500 Internal Server Error
            // ==================================================

            else if (status === 500) {

                alert(
                    '서버 내부 장애가 발생했습니다. 관리자에게 문의해 주세요.'
                );
            }


            // ==================================================
            // 기타 HTTP 오류
            // ==================================================

            else {

                alert(
                    `[오류 ${status}] ${serverMessage}`
                );
            }
        }


        // ====================================================
        // 요청은 보냈지만 응답을 받지 못한 경우
        // ====================================================

        else if (error.request) {

            alert(
                '백엔드 서버(8080 포트)와 통신할 수 없습니다. 서버 구동 상태나 네트워크 연결을 확인하세요.'
            );
        }


        // ====================================================
        // Axios 요청 생성 자체에서 오류
        // ====================================================

        else {

            alert(
                `클라이언트 요청 생성 오류: ${error.message}`
            );
        }


        // ====================================================
        // 원래 에러를 호출한 컴포넌트로 전달
        // ====================================================

        return Promise.reject(error);
    }
);


export default api;
